"""Rebuild evals/results/summary.md from the run JSON files: `python -m evals.summary`.

The table is regenerated (not appended), with metrics recomputed from each run's stored
per-question scores. Changing a metric definition and rebuilding updates every past row
consistently. Partial runs (--limit / --ids), invalid runs (API outage) and runs that were
later rescored are left out.
"""

import json
from dataclasses import fields
from pathlib import Path

from evals.metrics import QuestionScore, aggregate

RESULTS_DIR = Path(__file__).resolve().parent / "results"
SUMMARY_PATH = RESULTS_DIR / "summary.md"

HEADER = """# Eval results

Generated by `python -m evals.summary` from the run files in this folder. One row per full run.

- **Exec acc**: answerable questions whose result set matches the gold result.
- **Easy / Medium / Hard**: execution accuracy within each difficulty (answerable questions only).
- **Abstain acc**: refuse/clarify questions where the agent did not answer.
- **Overall**: every question, counting correct abstentions as correct.
- **Spec**: version of docs/schema.yaml the run used (business rules change prompts and gold).
- With 74 answerable test questions, one question is about 1.4 points of execution accuracy,
  so differences of 1-2 questions are within run-to-run noise. Runs with N=66 used the
  benchmark before it was hardened (D24).

| Run (UTC) | Agent | Model | Spec | Split | N | Exec acc % | Easy % | Medium % | Hard % | Abstain acc % | Overall % | Valid SQL % | p50 s | p95 s | Avg tokens in / out | $ / question | Total $ | Commit | Notes |
|---|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|---|---|
"""

_FIELDS = {f.name for f in fields(QuestionScore)}


def load_scores(run: dict) -> list[QuestionScore]:
    """Rebuild QuestionScore objects from a run file (tolerates older files' missing fields)."""
    return [QuestionScore(**{k: v for k, v in q.items() if k in _FIELDS}) for q in run["questions"]]


def _fmt(v) -> str:
    return "–" if v is None else str(v)


def _row(meta: dict, m: dict) -> str:
    d = m["by_difficulty"]
    acc = {k: _fmt(d.get(k, {}).get("accuracy")) for k in ("easy", "medium", "hard")}
    secs = {
        k: _fmt(round(m[k] / 1000, 1)) if m[k] else "–"
        for k in ("latency_ms_p50", "latency_ms_p95")
    }
    note = "rescored" if meta.get("rescored_from") else ""
    return (
        f"| {meta['run_at'][:16].replace('T', ' ')} | {meta['agent_version']} | {meta['model']} | "
        f"v{meta.get('schema_doc_version', 1)} | {meta['split']} | {m['n']} | **{_fmt(m['execution_accuracy'])}** | {acc['easy']} | "
        f"{acc['medium']} | {acc['hard']} | {_fmt(m['abstention_accuracy'])} | "
        f"{_fmt(m['overall_accuracy'])} | {_fmt(m['valid_sql_rate'])} | "
        f"{secs['latency_ms_p50']} | {secs['latency_ms_p95']} | "
        f"{m['avg_input_tokens']:,} / {m['avg_output_tokens']:,} | {_fmt(m['avg_cost_usd'])} | "
        f"{_fmt(m['total_cost_usd'])} | {meta['commit']} | {note} |\n"
    )


def rebuild_summary(results_dir: Path = RESULTS_DIR, out: Path = SUMMARY_PATH) -> str:
    runs, superseded = [], set()
    for path in sorted(results_dir.glob("*.json")):
        run = json.loads(path.read_text())
        meta = run["meta"]
        if meta.get("rescored_from"):
            superseded.add(meta["rescored_from"])
        if not meta.get("partial") and not meta.get("invalid"):
            runs.append((path.name, run))
    # A rescored run replaces the run it was rescored from.
    runs = [run for name, run in runs if name not in superseded]
    runs.sort(key=lambda r: r["meta"]["run_at"])
    text = HEADER + "".join(_row(r["meta"], aggregate(load_scores(r))) for r in runs)
    out.write_text(text)
    return text


if __name__ == "__main__":
    print(rebuild_summary())
